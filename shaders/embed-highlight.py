#!/usr/bin/env python3
"""Embed the two offline GXP programs without requiring a compiler on Vita."""
from pathlib import Path
import sys

if len(sys.argv) != 4:
    raise SystemExit("usage: embed-highlight.py normal.gxp additive.gxp output.h")
lines = ["/* Generated by shaders/build-highlight.cpp; see shaders/README.md. */"]
for source, name in zip(sys.argv[1:3], ("highlight_fragment_gxp", "highlight_add_fragment_gxp")):
    data = Path(source).read_bytes()
    if data[:3] != b"GXP":
        raise SystemExit(f"invalid GXP header: {source}")
    lines.append(f"static const unsigned char {name}[] __attribute__((aligned(64))) = {{")
    lines.extend("  " + ",".join(f"0x{x:02x}" for x in data[i:i + 16]) + "," for i in range(0, len(data), 16))
    lines.append("};")
Path(sys.argv[3]).write_text("\n".join(lines) + "\n")
